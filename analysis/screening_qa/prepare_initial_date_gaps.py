"""Freeze source-only independent date followups for already saved new initials.

This locates unperformed metadata obligations; it makes no date or eligibility
judgments and exposes no other-pass decisions to workers.
"""
import argparse
from collections import Counter
from pathlib import Path
import resume_screening as s

p=argparse.ArgumentParser();p.add_argument('--snapshot',required=True);a=p.parse_args()
assert a.snapshot.replace('-','').replace('_','').isalnum()
can=s.RUN/'canonical';inventory=s.inv()
initial={pas:{row['publication_id']:row for row in s.rd(can/f'pass-{pas}-original-initials.csv')} for pas in 'AB'}
queue=can/'independent-2020-date-obligations.csv'
prior=set()
for receipt in (s.RUN/'initial-date-gap-audit').glob('*/manifest.csv'):
    prior.update((row['pass_id'],row['publication_id']) for row in s.rd(receipt))
tasks=[]
for row in s.rd(queue):
    if not row['date_check_status'].startswith('PENDING'):continue
    pas=row['pass_id'];key=row['publication_id'];own=initial[pas][key]
    worker=own.get('worker_id')
    if not worker or (pas,key) in prior:continue
    assert worker in s.WORKERS and worker[0]==pas
    tasks.append({'publication_id':key,'pass_id':pas,'worker_id':worker,'obligation':'independent_2020_date','initial_artifact':own['initial_artifact'],'initial_artifact_sha256':own['initial_artifact_sha256'],'dispatch_status':'UNPERFORMED','source_inventory_sha256':s.EXPECTED_HASH})
assert len(tasks)==len({(row['pass_id'],row['publication_id']) for row in tasks})
dest=s.RUN/'initial-date-gap-audit'/a.snapshot;dest.mkdir(parents=True,exist_ok=False)
s.wr(dest/'manifest.csv',tasks,exclusive=True)
with (dest/'date-status-at-dispatch.csv').open('xb') as f:f.write(queue.read_bytes())
packets={}
for worker in s.WORKERS:
    own=[row for row in tasks if row['worker_id']==worker]
    if not own:continue
    packet=s.RUN/'workers'/worker/f'date-gap-source-only-{a.snapshot}.csv'
    s.wr(packet,[inventory[row['publication_id']]|{'obligation':'independent_2020_date'} for row in own],exclusive=True)
    packets[worker]={'file':packet.as_posix(),'sha256':s.sha(packet),'n':len(own)}
receipt={'generated_at_utc':s.stamp(),'snapshot':a.snapshot,'inventory_sha256':s.EXPECTED_HASH,'manifest_sha256':s.sha(dest/'manifest.csv'),'dispatch_status_sha256':s.sha(dest/'date-status-at-dispatch.csv'),'n':len(tasks),'by_worker':dict(Counter(row['worker_id'] for row in tasks)),'source_only_packets':packets,'scope':'Independent own-source date checks for saved new initials only. No other-pass labels or prior proposed date outcomes in worker packets. Actual source attempts, checked-unresolved outcomes and later corrections remain separately authored. No dates or scientific classifications generated by this script.'}
s.js(dest/'receipt.json',receipt,exclusive=True)
print(receipt)
